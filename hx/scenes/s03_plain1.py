def _lagged_x(t: float) -> float:
    """The child's ground x averaged over the last beat: what the camera and the scribble follow
    (a step's own rocking is averaged out; it has arrived a beat after the child)."""
    if t <= T_GO:
        return X2
    return sum(AC.s03(t - BEAT * i / 6.0).x for i in range(6)) / 6.0


# the two turns of the performance (58.86 its back to us, 74.94 round to the line) carry the face over the edge
# of the head in two or three frames: a tired child does not snap round. The act's clock is slowed about
# the moment the face crosses (0.28 of its speed; 1.4 times a quarter of the window either side; smooth at its ends)
_SLOW = ((59.07, 0.28), (75.05, 0.28))
_SLOW_K = 0.36


def _act_t(t: float) -> float:
    for c, hw in _SLOW:
        u = (t - c + hw) / (2.0 * hw)
        if 0.0 < u < 1.0:
            return t + 2.0 * hw * _SLOW_K / (2.0 * math.pi) * (math.sin(2.0 * math.pi * u) - 0.5 * math.sin(4.0 * math.pi * u))
    return t


# the turns on the spot (figure.turn_round): it picks up the near foot in the first half and the far one in the
# second, but the foot on the ground slides with the turn (up to 8 units a frame, 32 in all: the flat projection moves an
# ankle as the body turns over it). Here each foot is set where it stands at the end of the turn while it is in the air,
# and pinned while it is down: (start, length) on the act's clock (AC.S03_T: turn, walk - turn - 0.06; arrive + 0.34, 0.52)
_TURNS = tuple((t0, d, AC.s03(t0).pose, AC.s03(t0 + d).pose) for t0, d in ((58.86, 59.515 - 58.86 - 0.06), (74.94, 0.52)))


def _pin_turn_feet(a, ta: float) -> None:
    for t0, dur, P0, P1 in _TURNS:
        w = (ta - t0) / dur
        if not 0.0 < w < 1.0:
            continue
        f0, f1, b0, b1 = _ankle_x(P0, "ff"), _ankle_x(P1, "ff"), _ankle_x(P0, "fb"), _ankle_x(P1, "fb")
        if w < 0.5:
            tgt = {"ff": f0 + (f1 - f0) * ease(w / 0.5), "fb": b0}
        else:
            tgt = {"ff": f1, "fb": b0 + (b1 - b0) * ease((w - 0.5) / 0.5)}
        P = a.pose
        yt = P["turn"] * math.pi / 2.0
        ct = math.cos(yt)
        se = math.sin(yt + OPEN_K * P["open"] * ct * abs(ct) * math.pi / 2.0)
        n = ct * ct + se * se
        kw = {}
        for key, sg in (("ff", 1.0), ("fb", -1.0)):          # the least change of the foot's x and z that puts its ankle there
            err = tgt[key] - _ankle_x(P, key)
            kw[key] = (P[key][0] + err * ct / n, P[key][1])
            kw[key + "z"] = P[key + "z"] - sg * err * se / n
        a.pose = P.but(**kw)
        a.J = pose_joints(a.pose, a.x, a.y, a.h, a.face)
        a.pts["crown"], a.pts["mouth"] = a.J["crown"], a.J["mouth"]
        return


def _knock(t: float) -> float:
    j = 0.0
    for h, k in ((SPAN[0] + 1.0 / 30.0, 0.45), (HITS[0], 1.0), (HITS[1], 1.0), (HITS[2], 1.0)):
        d = t - h
        if 0.0 <= d < 0.6:
            j += k * math.exp(-d / 0.09) * math.cos(d * 38.0)
    return j


# the travelling shot of the walk home: where the camera's centre is (time, world x, units a second). It sets
# off after the child, runs a little ahead of it to show where it is going (the child falls back to the left
# third), and is nearly at rest on the room when the child walks to its place on the rug
_TRAVEL = ((79.0, CLOSE.cx, 0.0), (81.0, 2690.0, 190.0), (85.3, 3580.0, 175.0), (90.9, S.CAM[END].cx, 0.0))


def _travel_x(t: float) -> float:
    for (t0, p0, v0), (t1, p1, v1) in zip(_TRAVEL, _TRAVEL[1:]):
        if t < t1:
            h = t1 - t0
            u = (t - t0) / h
            return ((2 * u ** 3 - 3 * u ** 2 + 1) * p0 + (u ** 3 - 2 * u ** 2 + u) * h * v0 + (3 * u ** 2 - 2 * u ** 3) * p1
                    + (u ** 3 - u ** 2) * h * v1)
    return _TRAVEL[-1][1]


def _camera(t: float) -> Cam:
    if t < T_IN[0]:
        c = Cam.ease(S.CAM[START], WIDE, seg(t, *T_PULL))
    elif t < _TRAVEL[0][0]:
        c = Cam.ease(WIDE, CLOSE, seg(t, *T_IN))
    elif t < _TRAVEL[-1][0]:
        w1, w2 = ease(seg(t, 79.3, 85.3)), ease(seg(t, 85.3, 90.9))      # it eases back to 0.8, then in to the room
        z = CLOSE.zoom * (0.8 / CLOSE.zoom) ** w1 * (1.0 / 0.8) ** w2
        c = Cam(_travel_x(t), FLOOR - (272.0 - 42.0 * w1 - 28.0 * w2) / z, z)
    else:
        return S.CAM[END]
    j = _knock(t)
    if j != 0.0:
        c = Cam(c.cx, c.cy + 7.0 * j / c.zoom, c.zoom * (1.0 + 0.004 * j))
    return c


def _far_cam(cam: Cam) -> Cam:
    """The camera of the far friend: a far thing keeps its place and its size on screen while the
    camera travels (in the wide frame it stands where land.tower_layout puts it), its feet on the
    horizon."""
    z = WIDE.zoom * (cam.zoom / WIDE.zoom) ** 0.06
    sx = WIDE.to_screen(FRIEND_X, FLOOR)[0] - 0.0185 * (cam.cx - WIDE.cx)
    return Cam.at(FRIEND_X, FLOOR, z, sx, cam.to_screen(0.0, FLOOR)[1])


class _HouseTone(Sketch):
    """The house's layer with the pressure of its colouring-in as a number of its own (Sketch.draw's
    pressure is one for lines and tone): its tone is rubbed away before its lines travel into the
    window, because sets.plain_to_room takes over strokes only."""

    def __init__(self, sk, k: float):
        super().__init__(sk.items)
        self.k = k

    def draw(self, F, d=None, a=1.0, thin=1.0, tint=None, tint_w=0.0, overlap=0.25):
        for it in self.items:
            k = self.k if isinstance(it, Fill) else 1.0
            if k > 0.0:
                Sketch([it]).draw(F, d, a * k, thin, tint, tint_w)


_DOOR_D = 0.6                                            # the two doors stand behind the house: a far layer


def _two_doors() -> Sketch:
    """The two doors behind the split house, one beside each half (the home is two homes now): plain
    doors of the kit, broad as a child draws a door, dim, far (150 px in the wide frame, whole under
    the lid, clear of the leaning halves), composed for the wide frame and moved to their far layer
    (as land's own far members are)."""
    hx_, hw_ = LAY.house["x"], LAY.house["w"]
    col = mix(C.CHALK_FAR, C.CHALK_DIM, 0.6)
    out = []
    for j, (xm, side) in enumerate(((hx_ - 0.5 * hw_ - 400.0, 1), (hx_ + 0.5 * hw_ + 450.0, -1))):
        d = door(-112.0, FLOOR - 506.0, 112.0, FLOOR, seed=1700 + 40 * j, col=col, mood="night", pane=False, side=side,
                 name=f"door{j}")
        out.append(d.place(xm, 0.0, 1.45, origin=(0.0, FLOOR)))
    k = WIDE.zoom ** (1.0 - _DOOR_D)
    return Sketch(out).place(CX + (WIDE.cx - CX) * _DOOR_D - WIDE.cx * k, CY + (WIDE.cy - CY) * _DOOR_D - WIDE.cy * k, k)


