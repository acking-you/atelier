    J = S.child(F, a, rim=S.amber_rim(rk) if rk > 0.0 else None)
    if a_pl > 0.0 and d_mist > 0.0:
        mist(F, a=a_pl, slab=(0.0, d_mist), **m_ends)       # the mist it has walked into
    if sp <= 0.0:
        S.scribble(F, cloud, J)
    elif not is_lid:
        scribble_form()
    S.rain_front(F, k_rain)

